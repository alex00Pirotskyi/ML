def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("train_folder", nargs="?", default="TAP_MODELS_F1_FILEFOLDS")
    ap.add_argument("--data", type=Path, default=ROOT / "DATA" / "DATA_TAP_F1")
    ap.add_argument("--parity-files", type=int, default=None, help="held-out recordings replayed in C (0: all)")
    a = ap.parse_args(argv)
    export_bundle(a.train_folder, a.data, a.parity_files)
    return 0


