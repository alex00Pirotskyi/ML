# ================================================================================================ model code
def model_code(text):
    """the export_plus header turned into the model part of tap_gestures.c, and its facts"""
    facts = {}
    for key, rx in (("platform", r"Model platform: (\S+)"), ("preprocessing", r"Training preprocessing: (\S+)"),
                    ("tree_bytes", r"Flash storage: [^;]+; (\d+) tree-data bytes"),
                    ("static_bytes", r"Total generated static model data: (\d+) bytes"),
                    ("n_inputs", r"#define TAP_NUM_FEATURES (\d+)u"), ("n_trees", r"#define TAP_NUM_TREES (\d+)u")):
        m = re.search(rx, text)
        facts[key] = (int(m.group(1)) if m.group(1).isdigit() else m.group(1)) if m else None
    for need in ("tap_predict_raw_score(", "tap_predict_q20(", "tap_q20_raw_thresholds["):
        if need not in text:
            raise ValueError(f"the model header has no {need!r}: not an export_plus TAP binary classifier")
    code = text
    code = re.sub(r"^#ifndef TAP_MODEL_H\s*\n#define TAP_MODEL_H\s*\n", "", code, flags=re.M)
    code = re.sub(r"\n#endif /\* TAP_MODEL_H \*/\s*$", "\n", code)
    code = code.replace('#include "core_type_def.h"\n', "")
    code = code.replace("p_core->diff(", "tg_diff(").replace("p_core->ratio(", "tg_ratio(")
    if "p_core->diff" in code or "p_core->ratio" in code:
        raise ValueError("an unexpected helper call is left in the model code")
    # profiling hooks (no code in the firmware build): trees and nodes walked
    code, n = re.subn(r"(TAP_FORCE_INLINE float tap_walk_\w+_tree\([^{]*\{\n)", r"\1    TG_PROFILE_TREE();\n", code)
    code, m = re.subn(r"(\n(\s+)const uint32_t absolute_index = [^\n]+\n)", r"\1\2TG_PROFILE_NODE();\n", code)
    facts["profiled"] = bool(n and m)
    fields = sorted(set(ACCESSOR.findall(code)))
    return code, facts, fields


# ================================================================================================ the three files
def core_typedef_h(tag, fields, stamp):
    lines = "\n".join(f" *   {f}" for f in fields)
    return f"""/*
 * core_typedef.h - what the TAP model reads from the feature core (t_core), for tap_gestures.c.
 * Generated by export_tap_bundle.py for {tag} ({stamp}).
 *
 * Firmware build: this file includes the firmware's own core_type_def.h (t_core, X / Y / Z, CH1..CH3, the history
 * sizes). Its t_core must hold these {len(fields)} fields, as logged (PSD codes 0..65535, acc_rate signed, Lean-lite
 * Q8 from lean_lite.h, updated once per EMG frame):
{lines}
 * Host replay and tests: build with -DTG_HOST_CORE and this file defines a t_core with those arrays itself.
 *
 * The two helpers are the arithmetic the model was trained on (tap_f1_features.FeatureMaker), as inline functions,
 * so tap_gestures.c does not use p_core->diff / p_core->ratio (no indirect call; signed inputs such as acc_rate work):
 *   tg_diff(a, b)  = a - b, saturated to int16
 *   tg_ratio(a, b) = (a + 1) / (b + 1), float
 */
#ifndef CORE_TYPEDEF_H
#define CORE_TYPEDEF_H

#include <stdint.h>

#if !defined(TG_HOST_CORE)
#include "core_type_def.h"
#else
#define X 0
#define Y 1
#define Z 2
#define CH1 0
#define CH2 1
#define CH3 2
#define ACC_PSD_HISTORY_SIZE 10
#define EMG_PSD_HISTORY_SIZE 15
typedef struct
{{
    uint16_t emg_psd[EMG_PSD_HISTORY_SIZE][3][5];
    uint16_t emg_psd_mean[3][5];
    uint16_t acc_psd[ACC_PSD_HISTORY_SIZE][3][6];
    uint16_t acc_psd_mean[3][6];
    int16_t  acc_rate[3][6];
    struct
    {{
        int16_t min10[3];
        int16_t max10[3];
        int16_t rise10[3];
        int16_t dev3[3];
        int16_t d01[3];
        int16_t range10[3];
        int16_t fall10[3];
        int16_t xm[3];
    }} cload_lite;
}} t_core;
#endif

static inline int16_t tg_diff(int32_t a, int32_t b)
{{
    const int32_t d = a - b;
    return (int16_t) (d > 32767 ? 32767 : (d < -32768 ? -32768 : d));
}}

static inline float tg_ratio(int32_t a, int32_t b)
{{
    return ((float) a + 1.0f) / ((float) b + 1.0f);
}}

#endif /* CORE_TYPEDEF_H */
"""


def tap_gestures_h(tag, choice, facts, cost, stamp):
    n = choice["nominal"]
    s = choice.get("stress") or {}
    hum = [v for k, v in s.items() if k.startswith("hum")]
    stress_line = ""
    if s:
        stress_line = (f"\n *   with band changes: placement {100 * s['placement']['taps']:.1f}% / {s['placement']['false_pm']:.2f} per min, "
                       f"rotation {100 * s['rotation']['taps']:.1f}% / {s['rotation']['false_pm']:.2f}, power-grid hum (worst zone) "
                       f"{100 * min(v['taps'] for v in hum):.1f}% / {max(v['false_pm'] for v in hum):.2f}")
    rule_line = ""
    if "se_rule" in choice and "fire_best_u_q20" in choice:
        rule_line = (f"\n *   FIRE: the highest within {choice['se_rule']:g} standard error(s) of the best U (best at "
                     f"{choice['fire_best_u_q20'] / 20:.2f}), so thin evidence leans to fewer false taps; every FIRE is "
                     f"in backtest.md\n *   (define TG_FIRE_Q20 / TG_SECOND_Q20 at build time to move along it).")
    cost_line = ""
    if cost:
        cost_line = (f"\n * Cost: {cost.get('arm_text', '?')} bytes of Cortex-M4F code + constants (clang -Os), "
                     f"{cost.get('ram_state', 12)} bytes of state; tree nodes per frame {cost['nodes_mean']:.0f} on average "
                     f"(early exit), {cost['nodes_p99']:.0f} at the 99th percentile, {cost['nodes_max']:.0f} at most "
                     f"(full score: {cost['nodes_full_mean']:.0f}).")
    return f"""/*
 * tap_gestures.h - TAP / DOUBLE_TAP from the feature core, one call per model run.
 * Generated by export_tap_bundle.py for {tag} ({stamp}); model and logic in tap_gestures.c,
 * inputs in core_typedef.h.
 *
 *   static tg_state_t m_tap;                     // tg_init(&m_tap, now_ms) at start-up and when the stream restarts
 *   ...
 *   switch (tg_process(&m_tap, &m_feat_core, now_ms)) {{   // after the core (and lean_lite_update) is current
 *       case TG_TAP:        ... single tap ...;  break;
 *       case TG_DOUBLE_TAP: ... double tap ...;  break;
 *       default:            break;
 *   }}
 *
 * Rule (deferred mode, the default): a tap starts on a rising edge of the model score to >= TG_FIRE_Q20 / 20,
 * 150 ms refractory. A 2nd tap 150..400 ms later, after the score dipped below TG_DIP_Q20 / 20, with a score
 * >= TG_SECOND_Q20 / 20, reports TG_DOUBLE_TAP (then 300 ms lockout); otherwise TG_TAP is reported when the 400 ms
 * window closes. TG_REPORT_TAP_IMMEDIATELY 1: TG_TAP at once, TG_DOUBLE_TAP follows (the app undoes the tap).
 * Thresholds compare the raw tree score against exact float32 logits of k / 20: no expf / logf.
 *
 * Back test (backtest_tap_f1.py, held-out fold {choice['fold']}, {choice['recordings']} recordings, never trained on):
 *   taps {100 * n['taps']:.1f}% of pointer presses (soft {100 * n['soft']:.1f}%, 240 bpm {100 * n['fast240']:.1f}%), double taps as
 *   DOUBLE_TAP {100 * n['double_pairs']:.1f}%, single taps read as DOUBLE_TAP {100 * n['single_as_double']:.1f}%;
 *   false TAP / DOUBLE_TAP {n['false_pm']:.2f} per minute of movement (fist {n['false_fist_pm']:.2f}, finger {n['false_finger_pm']:.2f},
 *   wrist {n['false_wrist_pm']:.2f}, arm {n['false_arm_pm']:.2f}, band {n['false_band_pm']:.2f}){stress_line}{rule_line}
 * Model: {facts.get('platform')}, {facts.get('n_trees')} trees, {facts.get('n_inputs')} inputs, {facts.get('static_bytes')} bytes of tables, preprocessing {facts.get('preprocessing')}.{cost_line}
 */
#ifndef TAP_GESTURES_H
#define TAP_GESTURES_H

#include <stdint.h>
#include "core_typedef.h"

#ifndef TG_FIRE_Q20
    #define TG_FIRE_Q20 ({int(choice['fire_q20'])}u)          /* {choice['fire_q20'] / 20:.2f}: tap onset (rising edge), chosen by the back test */
#endif
#ifndef TG_SECOND_Q20
    #define TG_SECOND_Q20 ({int(choice['second_q20'])}u)        /* {choice['second_q20'] / 20:.2f}: 2nd tap of a double */
#endif
#ifndef TG_DIP_Q20
    #define TG_DIP_Q20 ({int(choice['dip_q20'])}u)            /* {choice['dip_q20'] / 20:.2f}: the score must fall below this between the taps */
#endif
#ifndef TG_MIN_GAP_MS
    #define TG_MIN_GAP_MS ({int(choice['min_gap_ms'])}u)
#endif
#ifndef TG_WINDOW_MS
    #define TG_WINDOW_MS ({int(choice['window_ms'])}u)
#endif
#ifndef TG_LOCKOUT_MS
    #define TG_LOCKOUT_MS ({int(choice['lockout_ms'])}u)
#endif
#ifndef TG_REPORT_TAP_IMMEDIATELY
    #define TG_REPORT_TAP_IMMEDIATELY (0)
#endif
#ifndef TG_CHAIN_TAPS
    #define TG_CHAIN_TAPS (0)
#endif
#if (TG_CHAIN_TAPS != 0) && (TG_REPORT_TAP_IMMEDIATELY == 0)
    #error "TG_CHAIN_TAPS needs TG_REPORT_TAP_IMMEDIATELY 1"
#endif
#if (TG_DIP_Q20 < 1u) || (TG_DIP_Q20 >= TG_SECOND_Q20) || (TG_SECOND_Q20 > TG_FIRE_Q20) || (TG_FIRE_Q20 > 19u)
    #error "need 1 <= TG_DIP_Q20 < TG_SECOND_Q20 <= TG_FIRE_Q20 <= 19"
#endif

typedef enum
{{
    TG_NONE = 0,
    TG_TAP,
    TG_DOUBLE_TAP,
}} tg_event_t;

typedef struct
{{
    uint32_t t_first;      /* ms, onset of the pending tap */
    uint32_t t_last;       /* ms, last accepted onset */
    uint8_t  state;        /* idle / pending / lockout */
    uint8_t  above_fire;   /* the previous score was >= TG_FIRE_Q20 (rising edges) */
    uint8_t  dipped;
    uint8_t  reserved;
}} tg_state_t;

/* Start, or restart after the stream stopped or the model was gated off. */
void tg_init(tg_state_t* s, uint32_t now_ms);

/* One model run on the current core; returns TG_TAP, TG_DOUBLE_TAP or TG_NONE. now_ms: a millisecond clock (wraps). */
tg_event_t tg_process(tg_state_t* s, const t_core* p_core, uint32_t now_ms);

/* Drop a pending tap that was not reported yet (deferred mode), e.g. a swipe or long press was recognised. */
void tg_cancel(tg_state_t* s);

/* The model score as Q20 (0..20, nearest 0.05), for logs; not needed by tg_process. */
uint8_t tg_score_q20(const t_core* p_core);

#endif /* TAP_GESTURES_H */
"""


def tap_gestures_c(tag, code, stamp):
    return f"""/*
 * tap_gestures.c - the TAP model ({tag}) and the tap / double-tap logic. Generated by export_tap_bundle.py
 * ({stamp}); see tap_gestures.h. The model part is export_plus.py's code with the helpers inlined.
 */
#include "tap_gestures.h"

#include <math.h>
#include <stdint.h>

#ifndef TG_PROFILE_TREE
    #define TG_PROFILE_TREE() ((void) 0)
#endif
#ifndef TG_PROFILE_NODE
    #define TG_PROFILE_NODE() ((void) 0)
#endif

/* ============================================================================ the model (export_plus) */
{code}
/* ============================================================================ the tap logic */
enum
{{
    TG_IDLE = 0,
    TG_PENDING, /* one tap seen, waiting for a 2nd */
    TG_LOCKOUT, /* just reported a double tap */
}};

void tg_init(tg_state_t* s, uint32_t now_ms)
{{
    s->state      = TG_IDLE;
    s->above_fire = 0u;
    s->dipped     = 0u;
    s->reserved   = 0u;
    s->t_first    = now_ms;
    s->t_last     = now_ms - TG_LOCKOUT_MS - TG_MIN_GAP_MS; /* no refractory right after a start */
}}

void tg_cancel(tg_state_t* s)
{{
    if (s->state == TG_PENDING)
    {{
        s->state = TG_IDLE;
    }}
}}

uint8_t tg_score_q20(const t_core* p_core)
{{
    return tap_probability_q20(p_core);
}}

tg_event_t tg_process(tg_state_t* s, const t_core* p_core, uint32_t now_ms)
{{
    tg_event_t ev = TG_NONE;
    uint8_t above_fire;
    uint8_t above_second = 0u;
    uint8_t below_dip    = 0u;

    if (s->state == TG_PENDING)
    {{
        /* a tap is pending (at most TG_WINDOW_MS): the full score once, three thresholds */
        const float raw = tap_predict_raw_score(p_core);
        above_fire      = (uint8_t) (raw >= tap_q20_raw_thresholds[TG_FIRE_Q20 - 1u]);
        above_second    = (uint8_t) (raw >= tap_q20_raw_thresholds[TG_SECOND_Q20 - 1u]);
        below_dip       = (uint8_t) (raw < tap_q20_raw_thresholds[TG_DIP_Q20 - 1u]);
    }}
    else
    {{
        /* most frames: only "score >= FIRE?", early exit after the first trees that settle it */
        above_fire = (uint8_t) (tap_predict_q20(p_core, (uint8_t) TG_FIRE_Q20) != 0);
    }}
    const uint8_t rising = (uint8_t) ((above_fire != 0u) && (s->above_fire == 0u));
    s->above_fire        = above_fire;

    if (s->state == TG_PENDING)
    {{
        const uint32_t dt = now_ms - s->t_first;
        if (below_dip != 0u)
        {{
            s->dipped = 1u;
        }}
        if ((dt >= TG_MIN_GAP_MS) && (dt <= TG_WINDOW_MS) && (s->dipped != 0u) && (above_second != 0u))
        {{
#if (TG_CHAIN_TAPS != 0)
            s->t_first = now_ms; /* stay pending: the next tap of a fast series counts too */
            s->dipped  = 0u;
#else
            s->state = TG_LOCKOUT;
#endif
            s->t_last = now_ms;
            return TG_DOUBLE_TAP;
        }}
        if (dt <= TG_WINDOW_MS)
        {{
            return TG_NONE;
        }}
        s->state = TG_IDLE; /* the window closed: it was a single tap */
#if (TG_REPORT_TAP_IMMEDIATELY == 0)
        ev = TG_TAP;
#endif
    }}
    if (s->state == TG_LOCKOUT)
    {{
        if ((now_ms - s->t_last) < TG_LOCKOUT_MS)
        {{
            return TG_NONE;
        }}
        s->state = TG_IDLE;
    }}
    if ((rising != 0u) && ((now_ms - s->t_last) >= TG_MIN_GAP_MS))
    {{
        s->state   = TG_PENDING;
        s->t_first = now_ms;
        s->t_last  = now_ms;
        s->dipped  = 0u;
#if (TG_REPORT_TAP_IMMEDIATELY != 0)
        ev = TG_TAP;
#endif
    }}
    return ev;
}}
"""


# ================================================================================================ checks
def _cc():
    return shutil.which("cc") or shutil.which("gcc") or shutil.which("clang")


def compile_host(fw, fields, build):
    """shared library of the bundle + a replay shim (host only: fills a t_core per row, counts trees and nodes)"""
    fill = "\n".join(f"    c->{f[len('p_core->'):]} = x[{k}];" for k, f in enumerate(fields))
    shim = f"""#include <string.h>
#include "core_typedef.h"
#include "tap_gestures.h"
extern unsigned long long tg_profile_trees, tg_profile_nodes;
static void fill(t_core* c, const float* x)
{{
{fill}
}}
void replay(const float* x, const uint32_t* t, long rows, signed char* ev, unsigned* nodes, unsigned* trees)
{{
    t_core c; tg_state_t s;
    memset(&c, 0, sizeof c);
    tg_init(&s, t[0]);
    for (long i = 0; i < rows; ++i)
    {{
        fill(&c, x + i * {len(fields)});
        const unsigned long long n0 = tg_profile_nodes, t0 = tg_profile_trees;
        ev[i] = (signed char) tg_process(&s, &c, t[i]);
        nodes[i] = (unsigned) (tg_profile_nodes - n0); trees[i] = (unsigned) (tg_profile_trees - t0);
    }}
}}
void score_full(const float* x, long rows, float* raw, unsigned* nodes)
{{
    t_core c; memset(&c, 0, sizeof c);
    for (long i = 0; i < rows; ++i)
    {{
        fill(&c, x + i * {len(fields)});
        const unsigned long long n0 = tg_profile_nodes;
        raw[i] = tap_predict_raw_score_export(&c);
        nodes[i] = (unsigned) (tg_profile_nodes - n0);
    }}
}}
"""
    build.mkdir(parents=True, exist_ok=True)
    prof = ("-DTG_PROFILE_TREE()=(++tg_profile_trees)", "-DTG_PROFILE_NODE()=(++tg_profile_nodes)")
    # the profiled library: tap_gestures.c + an export of the raw score + the counters
    (build / "prof.c").write_text('unsigned long long tg_profile_trees = 0, tg_profile_nodes = 0;\n'
                                  '#include "tap_gestures.c"\n'
                                  'float tap_predict_raw_score_export(const t_core* p_core) '
                                  '{ return tap_predict_raw_score(p_core); }\n')
    (build / "decl.h").write_text('#include "tap_gestures.h"\nfloat tap_predict_raw_score_export(const t_core* p_core);\n')
    shim = shim.replace('#include "tap_gestures.h"', '#include "decl.h"')
    (build / "shim.c").write_text(shim)
    lib = build / "libtapbundle.so"
    cmd = [_cc(), "-std=c99", "-O2", "-Wall", "-Wextra", "-Werror", "-Wno-unused-function", "-shared", "-fPIC",
           "-DTG_HOST_CORE", *prof, "-I", str(fw), "-I", str(build), str(build / "prof.c"), str(build / "shim.c"),
           "-o", str(lib), "-lm"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError("host build of the bundle failed:\n" + (r.stderr or r.stdout)[-4000:])
    # the bundle alone, as the firmware compiles it (no profiling, strict warnings)
    r = subprocess.run([_cc(), "-std=c99", "-O2", "-Wall", "-Wextra", "-Werror", "-Wshadow", "-Wconversion",
                        "-Wno-sign-conversion", "-Wno-float-conversion", "-Wno-unused-function", "-c", "-DTG_HOST_CORE",
                        "-I", str(fw), str(fw / "tap_gestures.c"), "-o", str(build / "tap_gestures.o")],
                       capture_output=True, text=True)
    strict = r.returncode == 0
    lib_ = ctypes.CDLL(str(lib))
    fp, up = ctypes.POINTER(ctypes.c_float), ctypes.POINTER(ctypes.c_uint32)
    lib_.replay.argtypes = [fp, up, ctypes.c_long, ctypes.POINTER(ctypes.c_byte), ctypes.POINTER(ctypes.c_uint),
                            ctypes.POINTER(ctypes.c_uint)]
    lib_.score_full.argtypes = [fp, ctypes.c_long, fp, ctypes.POINTER(ctypes.c_uint)]
    return lib_, strict, (r.stderr or "")[-2000:]


def arm_size(fw, build):
    """Cortex-M4F code + constant size of tap_gestures.c (clang, -Os), or None without a cross compiler"""
    clang, size = shutil.which("clang"), shutil.which("llvm-size") or shutil.which("size")
    if not clang or not size:
        return None
    inc = build / "arm_include"
    inc.mkdir(parents=True, exist_ok=True)
    (inc / "math.h").write_text("".join(f"#define {f}(x) __builtin_{f}(x)\n" for f in ("fabsf", "expf", "logf", "sqrtf")))
    obj = build / "tap_gestures_m4.o"
    r = subprocess.run([clang, "--target=thumbv7em-none-eabihf", "-mcpu=cortex-m4", "-mfloat-abi=hard", "-mfpu=fpv4-sp-d16",
                        "-Os", "-ffreestanding", "-std=c99", "-DTG_HOST_CORE", "-I", str(inc), "-I", str(fw), "-c",
                        str(fw / "tap_gestures.c"), "-o", str(obj)], capture_output=True, text=True)
    if r.returncode:
        return dict(error=(r.stderr or r.stdout)[-1500:])
    out = subprocess.run([size, str(obj)], capture_output=True, text=True).stdout.split("\n")
    vals = out[1].split() if len(out) > 1 else []
    return dict(text=int(vals[0]), data=int(vals[1]), bss=int(vals[2])) if len(vals) >= 3 else None


def parity(lib, choice, model, fields, names, files, max_files, log):
    """C events vs the Python back test on held-out recordings; nodes per frame"""
    import backtest_tap_f1 as BT
    import build_tap_f1_dataset as BUILD
    import evaluate_tap_f1 as EV
    import tap_f1_features as F
    import tap_gestures as TG
    cfg = TG.Config(fire=choice["fire_q20"], second=choice["second_q20"], dip=choice["dip_q20"],
                    min_gap_ms=choice["min_gap_ms"], window_ms=choice["window_ms"], lockout_ms=choice["lockout_ms"])
    rng = np.random.default_rng(0)
    pick = list(files) if (not max_files or len(files) <= max_files) else [files[i] for i in sorted(rng.choice(len(files), max_files, replace=False))]
    same = rows_total = ev_c = ev_py = 0
    differ = []
    nodes_all, nodes_full, trees_all = [], [], []
    for p in pick:
        rel = f"DATA_TAP/{p.parent.name}/{p.name}"
        df = pd.read_csv(BUILD._source(rel), low_memory=False)
        B, cols = BUILD.base_fields(df, rel, F.needs_lite(names) or any("cload_lite" in f for f in fields))
        ci = {c: i for i, c in enumerate(cols)}
        Xc = np.ascontiguousarray(B[:, [ci[f] for f in fields]], np.float32)
        t = np.round(df["Timestamp"].to_numpy(np.float64) - float(df["Timestamp"].iloc[0])).astype(np.uint32)
        n = len(df)
        ev = np.zeros(n, np.int8); nodes = np.zeros(n, np.uint32); trees = np.zeros(n, np.uint32)
        lib.replay(Xc.ctypes.data_as(ctypes.POINTER(ctypes.c_float)), t.ctypes.data_as(ctypes.POINTER(ctypes.c_uint32)),
                   n, ev.ctypes.data_as(ctypes.POINTER(ctypes.c_byte)), nodes.ctypes.data_as(ctypes.POINTER(ctypes.c_uint)),
                   trees.ctypes.data_as(ctypes.POINTER(ctypes.c_uint)))
        raw = np.zeros(n, np.float32); nf = np.zeros(n, np.uint32)
        lib.score_full(Xc.ctypes.data_as(ctypes.POINTER(ctypes.c_float)), n, raw.ctypes.data_as(ctypes.POINTER(ctypes.c_float)),
                       nf.ctypes.data_as(ctypes.POINTER(ctypes.c_uint)))
        X = F.FeatureMaker(cols, names)(B)
        q = BT.levels(EV._predict(model, X))
        py = TG.step_all(q, t.astype(np.float64), cfg)
        c_ev = [(int(i), int(e)) for i, e in zip(np.flatnonzero(ev), ev[ev != 0])]
        same += int(c_ev == py); rows_total += n; ev_c += len(c_ev); ev_py += len(py)
        if c_ev != py:
            differ.append(dict(file=p.name, c=len(c_ev), py=len(py), first_c=c_ev[:3], first_py=py[:3]))
        nodes_all.append(nodes); nodes_full.append(nf); trees_all.append(trees)
    nodes_all, nodes_full, trees_all = map(np.concatenate, (nodes_all, nodes_full, trees_all))
    out = dict(files=len(pick), identical_files=same, rows=rows_total, events_c=ev_c, events_python=ev_py,
               differ=differ[:10], nodes_mean=float(nodes_all.mean()), nodes_p99=float(np.percentile(nodes_all, 99)),
               nodes_max=float(nodes_all.max()), nodes_full_mean=float(nodes_full.mean()),
               trees_mean=float(trees_all.mean()))
    log(f"[bundle] C replay of {len(pick)} held-out recordings: {same} identical, events C {ev_c} / Python {ev_py}; "
        f"tree nodes per frame {out['nodes_mean']:.0f} mean, {out['nodes_p99']:.0f} p99 (full score {out['nodes_full_mean']:.0f})")
    return out


