def export_bundle(train_folder, data=ROOT / "DATA" / "DATA_TAP_F1", parity_files=None, log=print):
    import backtest_tap_f1 as BT
    train_folder = Path(train_folder)
    choice = json.loads((train_folder / "backtest_choice.json").read_text())
    tag = choice["model"]
    header = Path(choice.get("header") or train_folder / f"{tag}_model.h")
    if not header.is_file():
        header = train_folder / f"{tag}_model.h"
    code, facts, fields = model_code(header.read_text())
    wl_fields = [x for x in fields if WL_FIELD.search(x)]
    build_p = Path(data) / "_build" / "build.json"
    wl_on = bool(json.loads(build_p.read_text()).get("wl")) if build_p.is_file() else False
    if wl_fields and not wl_on:                   # WL, WL_head, WL_tail are removed: the firmware must not read them
        raise SystemExit(f"[bundle] {tag} reads {', '.join(wl_fields[:3])} but the data was built with WL off")
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    fw = train_folder / "firmware"
    fw.mkdir(parents=True, exist_ok=True)
    (fw / "core_typedef.h").write_text(core_typedef_h(tag, fields, stamp))
    (fw / "tap_gestures.c").write_text(tap_gestures_c(tag, code, stamp))
    (fw / "tap_gestures.h").write_text(tap_gestures_h(tag, choice, facts, None, stamp))   # cost added below
    with tempfile.TemporaryDirectory() as tmp:
        build = Path(tmp)
        lib, strict, warn = compile_host(fw, fields, build)
        arm = arm_size(fw, build)
        models = BT.load_models(train_folder)
        model = next(m for m in models if m["tag"] == tag)
        names = BT.schema_names(train_folder, models)
        files = BT.test_files(data, choice.get("fold", 0), ROOT / "DATA" / "fold_roadmap_files.json")
        n_par = int(parity_files if parity_files is not None else os.environ.get("TAP_F1_PARITY_FILES", 0)) or None
        par = parity(lib, choice, model["container"], fields, names, files, n_par, log)
    cost = dict(par, ram_state=12)
    if arm and "text" in arm:
        cost["arm_text"] = arm["text"] + arm["data"]
    (fw / "tap_gestures.h").write_text(tap_gestures_h(tag, choice, facts, cost, stamp))
    rep = dict(model=tag, header=str(header), choice=choice, facts=facts, fields=fields, wl_fields=wl_fields,
               arm=arm, parity=par,
               strict_warnings_clean=strict, strict_warnings=warn, stamp=stamp)
    (fw / "bundle.json").write_text(json.dumps(rep, indent=1, default=float))
    (fw / "BUNDLE.md").write_text(bundle_md(rep))
    if par["identical_files"] != par["files"]:
        log(f"[bundle] WARNING: {par['files'] - par['identical_files']} recordings fire differently in C (see bundle.json)")
    log(f"[bundle] {fw}: core_typedef.h, tap_gestures.h, tap_gestures.c ({facts.get('n_trees')} trees, "
        f"{facts.get('n_inputs')} inputs, Cortex-M4F {cost.get('arm_text', '?')} bytes)")
    return rep


