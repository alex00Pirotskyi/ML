#!/usr/bin/env python3
"""Firmware bundle of the TAP model the back test chose: core_typedef.h, tap_gestures.h, tap_gestures.c.

Reads TRAIN_FOLDER/backtest_choice.json (backtest_tap_f1.py: which model, FIRE / SECOND) and that model's export_plus
header (<tag>_model.h, written and checked against the Python model by train_tap_f1.py), and writes
TRAIN_FOLDER/firmware/:

  core_typedef.h   what the model reads from the feature core: in the firmware it includes core_type_def.h (t_core);
                   with -DTG_HOST_CORE it defines a t_core of those fields itself (host replay, tests). Plus the two
                   helpers as inline functions, with the exact arithmetic the model was trained on.
  tap_gestures.h   the API (tg_init, tg_process, tg_cancel), the back-tested settings (TG_FIRE_Q20, TG_SECOND_Q20, ...)
                   and the model's facts.
  tap_gestures.c   the model (trees, inputs) and the tap / double-tap logic. Cheap on purpose: while no tap is
                   pending it only asks "score >= FIRE?" with early exit (stops as soon as the remaining trees cannot
                   change the answer); only while a tap is pending (<= 400 ms) it computes the full score once.
  BUNDLE.md        the choice, back-test numbers, cost (Cortex-M4 code size, trees and nodes per frame), integration.

Then it checks the bundle: compiles it with -Wall -Wextra -Werror (host, and for Cortex-M4F with clang when present),
replays held-out recordings through the C and compares every event with the Python back test (twin of the logic:
research/gesture/tap_gestures.py), and measures the tree nodes walked per frame.

    python export_tap_bundle.py [TRAIN_FOLDER] [--data DATA/DATA_TAP_F1] [--parity-files N]
"""
