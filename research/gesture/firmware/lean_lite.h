#pragma once
/*
 * Lean-lite: integer, O(1) replacement for the Claude Lean-8 EMG features.
 *
 * 15 int16 model inputs (5 per EMG channel). No float, no division, no libm, no 64-bit math,
 * no history ring of samples: about 100 cycles per EMG frame on a Cortex-M4 and 164 bytes of state.
 *
 *   min10[ch]   floor of L = log2(WL + 1) over the last ~9-10 s           (Q8: 256 = one octave)
 *   max10[ch]   peak  of L over the last ~9-10 s                          (Q8)
 *   rise10[ch]  L - min10: activity above the recent floor                (Q8, >= 0)
 *   dev3[ch]    running mean of |L - running mean of L|, time constant 128 frames (~2.8 s), x8 (Q8)
 *   d01[ch]     emg_psd_mean[ch][0] - emg_psd_mean[ch][1] (codes are 10000*log10(1+power): a dB-like ratio)
 *
 * Dropped from Lean-8 (rarely used by the trees, or redundant): lw (trees split on wl directly),
 * Pm, r32. min10/max10 use 1-second blocks instead of an exact sliding window; sd3 became dev3.
 *
 * Call lean_lite_update() ONCE per new EMG feature frame (not per ACC tick), AFTER
 * psd_estemate_psd_mean() so d01 sees the current frame's PSD mean. Example glue:
 *
 *     static lean_lite_state_t m_lean_lite;           // zero at boot = reset
 *     ...
 *     emg_estimate_wl();
 *     emg_estimate_rms();
 *     psd_estemate_psd_mean(...);                      // the EMG PSD mean of THIS frame first
 *     {
 *         uint32_t     wl[3];
 *         uint16_t     pm[3 * 5];                         // emg_psd_mean[ch][z] at pm[ch * 5 + z]
 *         t_cload_lite out;
 *         for (uint32_t ch = 0u; ch < 3u; ++ch) {
 *             wl[ch] = (uint32_t) m_feat_core.wl[ch];
 *             for (uint32_t z = 0u; z < 5u; ++z) pm[ch * 5u + z] = (uint16_t) m_feat_core.emg_psd_mean[ch][z];
 *         }
 *         lean_lite_update(&m_lean_lite, wl, pm, &out);
 *         memcpy((void*) &m_feat_core.cload_lite, &out, sizeof(out));   // t_core is packed
 *     }
 *
 * and in t_core:   t_cload_lite cload_lite;   (the models read p_core->cload_lite.<field>[CHn]).
 * Copying in and out keeps every access aligned although t_core is __attribute__((packed)).
 *
 * Models trained with these inputs are meant to run only when lean_lite_ready() (500 frames, ~10.8 s
 * after a reset), the same gate the trainer evaluates on. Call lean_lite_reset() when the sensor
 * stream restarts (reconnect, band re-attached).
 *
 * The training data is generated by research/gesture/generate_lean_lite_features.py, which emulates
 * this file exactly and compiles it on the host to prove equality (integer: bit-exact).
 */

#include <stdint.h>
#include <string.h>

#ifndef LEAN_LITE_BLOCK_FRAMES
    #define LEAN_LITE_BLOCK_FRAMES (46u)  /* frames per min/max block: ~0.99 s at 46.3 EMG frames/s */
#endif
#define LEAN_LITE_BLOCKS       (10u)      /* window = the current block + the 9 previous complete blocks */
#define LEAN_LITE_RING         (LEAN_LITE_BLOCKS - 1u)
#define LEAN_LITE_EMA_SHIFT    (7u)       /* running mean / deviation: time constant 2^7 = 128 frames */
#define LEAN_LITE_DEV_SHIFT    (4u)       /* dev3 = deviation accumulator >> 4  (= mean |L - mean| x 8) */
#define LEAN_LITE_READY_FRAMES (500u)     /* frames after a reset before the models may run */

#if !defined(LEAN_LITE_HOST) && (defined(__ARM_ARCH) || defined(__arm__) || defined(__ICCARM__))
    /* CMSIS: arm_math.h (CMSIS-DSP) brings in cmsis_compiler.h (CMSIS-Core intrinsics). */
    #include "arm_math.h"
    #define LEAN_LITE_CLZ(x)         ((uint32_t) __CLZ(x))      /* one CLZ instruction */
    #define LEAN_LITE_SSAT16(x)      ((int16_t) __SSAT((x), 16)) /* one SSAT instruction */
    #define LEAN_LITE_MIN_Q15(p, n, r) do { uint32_t i_; arm_min_q15((p), (n), (r), &i_); } while (0)
    #define LEAN_LITE_MAX_Q15(p, n, r) do { uint32_t i_; arm_max_q15((p), (n), (r), &i_); } while (0)
#else
    /* Host build (training-data parity test): the same arithmetic without CMSIS. */
    static inline uint32_t lean_lite_host_clz(uint32_t x) { return x ? (uint32_t) __builtin_clz(x) : 32u; }
    static inline int16_t lean_lite_host_ssat16(int32_t x) { return (int16_t) (x > 32767 ? 32767 : (x < -32768 ? -32768 : x)); }
    static inline void lean_lite_host_min(const int16_t* p, uint32_t n, int16_t* r)
    {
        int16_t m = p[0];
        for (uint32_t i = 1u; i < n; ++i) m = p[i] < m ? p[i] : m;
        *r = m;
    }
    static inline void lean_lite_host_max(const int16_t* p, uint32_t n, int16_t* r)
    {
        int16_t m = p[0];
        for (uint32_t i = 1u; i < n; ++i) m = p[i] > m ? p[i] : m;
        *r = m;
    }
    #define LEAN_LITE_CLZ(x)           lean_lite_host_clz(x)
    #define LEAN_LITE_SSAT16(x)        lean_lite_host_ssat16(x)
    #define LEAN_LITE_MIN_Q15(p, n, r) lean_lite_host_min((p), (n), (r))
    #define LEAN_LITE_MAX_Q15(p, n, r) lean_lite_host_max((p), (n), (r))
#endif

/* The model inputs, as stored in t_core (30 bytes). */
typedef struct {
    int16_t min10[3];
    int16_t max10[3];
    int16_t rise10[3];
    int16_t dev3[3];
    int16_t d01[3];
} t_cload_lite;

/* Private state, 164 bytes. All zero = reset. */
typedef struct {
    int16_t  ring_min[3][LEAN_LITE_RING]; /* per complete block: min / max of L */
    int16_t  ring_max[3][LEAN_LITE_RING];
    int16_t  cur_min[3];                  /* the current (partial) block */
    int16_t  cur_max[3];
    int16_t  agg_min[3];                  /* over the complete blocks in the ring */
    int16_t  agg_max[3];
    int32_t  mean_acc[3];                 /* running mean of L, x 2^EMA_SHIFT (always >= 0) */
    int32_t  dev_acc[3];                  /* running mean of |L - mean|, x 2^EMA_SHIFT (always >= 0) */
    uint16_t in_block;                    /* frames already in the current block */
    uint16_t ring_fill;                   /* complete blocks in the ring (<= LEAN_LITE_RING) */
    uint16_t ring_head;                   /* next ring slot */
    uint16_t seen;                        /* frames since reset, saturates at LEAN_LITE_READY_FRAMES */
} lean_lite_state_t;

static inline void lean_lite_reset(lean_lite_state_t* s)
{
    (void) memset(s, 0, sizeof(*s));
}

static inline uint8_t lean_lite_ready(const lean_lite_state_t* s)
{
    return (uint8_t) (s->seen >= LEAN_LITE_READY_FRAMES);
}

/* L = log2(wl + 1) in Q8: integer part from CLZ, fraction = the 8 bits after the leading one
 * (piecewise-linear log2, max error 0.086 octave, exact at powers of two). Range 0..8191. */
static inline int32_t lean_lite_log2_q8(uint32_t wl)
{
    const uint32_t v = wl + (uint32_t) (wl != 0xFFFFFFFFu); /* wl + 1 without wrapping; >= 1 */
    const uint32_t n = 31u - LEAN_LITE_CLZ(v);              /* floor(log2(v)), 0..31 */
    return (int32_t) ((n << 8) | (((v << (31u - n)) >> 23) & 0xFFu));
}

/* wl: the 3 WL values; psd_mean: emg_psd_mean flattened, [ch][z] at psd_mean[ch * 5 + z] (only zones 0 and 1 are read). */
static inline void lean_lite_update(lean_lite_state_t* s, const uint32_t wl[3], const uint16_t psd_mean[15], t_cload_lite* out)
{
    const uint8_t first = (uint8_t) (s->seen == 0u);
    for (uint32_t ch = 0u; ch < 3u; ++ch)
    {
        const int32_t x = lean_lite_log2_q8(wl[ch]);

        /* min10 / max10: current block (running) and the 9 complete blocks before it. */
        if (s->in_block == 0u)
        {
            s->cur_min[ch] = (int16_t) x;
            s->cur_max[ch] = (int16_t) x;
        }
        else
        {
            if (x < s->cur_min[ch]) s->cur_min[ch] = (int16_t) x;
            if (x > s->cur_max[ch]) s->cur_max[ch] = (int16_t) x;
        }
        int32_t lo = s->cur_min[ch];
        int32_t hi = s->cur_max[ch];
        if (s->ring_fill != 0u)
        {
            if (s->agg_min[ch] < lo) lo = s->agg_min[ch];
            if (s->agg_max[ch] > hi) hi = s->agg_max[ch];
        }

        /* dev3: exponential running mean and mean absolute deviation, shifts only. */
        if (first)
        {
            s->mean_acc[ch] = x << LEAN_LITE_EMA_SHIFT;
            s->dev_acc[ch]  = 0;
        }
        s->mean_acc[ch] += x - (s->mean_acc[ch] >> LEAN_LITE_EMA_SHIFT);
        int32_t d = x - (s->mean_acc[ch] >> LEAN_LITE_EMA_SHIFT);
        if (d < 0) d = -d;
        s->dev_acc[ch] += d - (s->dev_acc[ch] >> LEAN_LITE_EMA_SHIFT);

        out->min10[ch]  = (int16_t) lo;
        out->max10[ch]  = (int16_t) hi;
        out->rise10[ch] = (int16_t) (x - lo);
        out->dev3[ch]   = LEAN_LITE_SSAT16(s->dev_acc[ch] >> LEAN_LITE_DEV_SHIFT);
        out->d01[ch]    = LEAN_LITE_SSAT16((int32_t) psd_mean[ch * 5u] - (int32_t) psd_mean[ch * 5u + 1u]);
    }

    /* Close the block once per ~second: push it into the ring and re-aggregate (CMSIS-DSP min/max). */
    if (++s->in_block >= LEAN_LITE_BLOCK_FRAMES)
    {
        const uint16_t head = s->ring_head;
        for (uint32_t ch = 0u; ch < 3u; ++ch)
        {
            s->ring_min[ch][head] = s->cur_min[ch];
            s->ring_max[ch][head] = s->cur_max[ch];
        }
        s->ring_head = (uint16_t) ((head + 1u) % LEAN_LITE_RING);
        if (s->ring_fill < LEAN_LITE_RING) s->ring_fill++;
        for (uint32_t ch = 0u; ch < 3u; ++ch)
        {
            LEAN_LITE_MIN_Q15(s->ring_min[ch], s->ring_fill, &s->agg_min[ch]);
            LEAN_LITE_MAX_Q15(s->ring_max[ch], s->ring_fill, &s->agg_max[ch]);
        }
        s->in_block = 0u;
    }
    if (s->seen < LEAN_LITE_READY_FRAMES) s->seen++;
}
